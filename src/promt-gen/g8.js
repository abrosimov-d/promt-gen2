export class g8 {
    constructor() {
        this.themes = [
            'мода', 'фитнес', 'здоровый образ жизни', 'стиль жизни', 
            'культура', 'еда', 'Instagram', 'глянцевый стиль'
        ];

        this.locations = [
            'в современной квартире', 'в студии', 'в уютном кафе', 
            'на городской улице', 'на пляже', 'в парке', 
            'в роскошном отеле', 'в художественной галерее'
        ];

        this.poses = [
            'стоит боком к камере', 'сидит на подоконнике', 
            'наклоняется вперед', 'оглядывается через плечо', 
            'вытягивает руки', 'скрещивает ноги', 
            'идет по улице', 'лежит на диване',
            'прислонилась к стене', 'присела на корточки'
        ];

        this.clothing = [
            'вечернее платье', 'спортивный топ и лосины', 
            'свитер с открытым плечом', 'полупрозрачная блузка', 
            'рубашка с кружевным бельем', 'легкий шелковый халат',
            'кожаная куртка', 'джинсы с облегающим топом',
            'платье-комбинация', 'спортивный костюм'
        ];

        this.lighting = [
            'мягкий естественный свет из окна', 'золотой час', 
            'студийный свет', 'контровой свет', 
            'неоновая подсветка', 'рассеянный дневной свет',
            'теплый вечерний свет', 'драматическое боковое освещение'
        ];

        this.quality = [
            'высокое разрешение', 'профессиональная съемка', 
            'глянцевая обработка', 'художественная композиция', 
            'малая глубина резкости', 'фокус на модели', 
            'идеальная кожа', 'профессиональная ретушь',
            'премиальное качество', 'фотография для глянца'
        ];

        this.styles = [
            'элегантный', 'чувственный', 'гламурный', 
            'естественный', 'художественный', 'модный',
            'романтичный', 'драматичный'
        ];
    }

    getRandomElement(array) {
        return array[Math.floor(Math.random() * array.length)];
    }

    generatePrompt() {
        const theme = this.getRandomElement(this.themes);
        const location = this.getRandomElement(this.locations);
        const pose = this.getRandomElement(this.poses);
        const clothing = this.getRandomElement(this.clothing);
        const lighting = this.getRandomElement(this.lighting);
        const quality = this.getRandomElement(this.quality);
        const style = this.getRandomElement(this.styles);

        return `Профессиональная фотография молодой женщины в ${style} стиле ${theme}: она ${pose}, одета в ${clothing}. ${location}. Освещение — ${lighting}. Атмосфера — глянцевая, с эффектом студийной ретуши. Качество: ${quality}, профессиональная съемка, идеальная композиция.`;
    }
}
