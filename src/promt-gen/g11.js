export class g11 {
    constructor() {
        this.settings = [
            "в спальне с бархатными шторами",
            "в роскошной ванной комнате с зеркалами",
            "на кровати утром, с рассеянным светом",
            "в полумраке с точечным светом на теле",
            "в стиле boudoir с мягкими подушками"
        ];

        this.clothing = [
            "в чёрном кружевном комплекте нижнего белья",
            "в полупрозрачной рубашке, слегка прикрывающей бёдра",
            "в корсете и чулках с открытыми бёдрами",
            "в шелковом халате, распахнутом спереди",
            "в мини-платье, собранном в складки у бёдер"
        ];

        this.poses = [
            "лёжа, одна нога согнута, другая вытянута",
            "полусидя, рука под платьем, чуть выше колена",
            "в положении полулёжа, волосы разбросаны по подушке",
            "в профиль, с акцентом на живот и бёдра",
            "в зеркальной позе, рука касается внутренней стороны бедра"
        ];

        this.lighting = [
            "мягкое свечение ночника рядом с кроватью",
            "рассеянный свет через шторы утром",
            "золотистый свет заката",
            "свет свечей на полу возле кровати",
            "точечный свет, фокусирующийся на лице и груди"
        ];

        this.themes = [
            "женская чувственность и здоровье",
            "ор+газм как часть женского благополучия",
            "эр+отическое самопознание",
            "интимная уверенность и безопасность",
            "тело как источник силы и удовольствия"
        ];

        this.models = [
            "женщина европеоидного типа",
            "темнокожая модель",
            "азиатская девушка",
            "латиноамериканская модель"
        ];
    }

    getRandomElement(array) {
        return array[Math.floor(Math.random() * array.length)];
    }

    generatePrompt() {
        const setting = this.getRandomElement(this.settings);
        const outfit = this.getRandomElement(this.clothing);
        const pose = this.getRandomElement(this.poses);
        const light = this.getRandomElement(this.lighting);
        const theme = this.getRandomElement(this.themes);
        const model = this.getRandomElement(this.models);

        const prompt = `
            Фотосессия профессиональной модели (${model}), ${setting}, одета в ${outfit}, поза: ${pose}, освещение: ${light}. Тема: ${theme}. Акцент на естественной красоте, уверенности в теле, женской анатомии и важности ор+газма для здоровья. Реалистичный, чувственный стиль, высокая детализация.
        `.trim().replace(/\s+/g, ' ');

        return prompt.substring(0, 500);
    }
}