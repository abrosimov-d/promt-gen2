    getRandomElement(array) {
        return array[Math.floor(Math.random() * array.length)];
    }

    generatePrompt(options = {}) {
        const opts = options && typeof options === 'object' ? options : {};
        const {
            style = '8k, резкий фокус, editorial quality',
            mood = 'дерзкий, уверенный, instagram mood',
        } = opts;

        const isSwimwear = Math.random() < 0.5;
        const outfit = isSwimwear ? this.getRandomElement(this.swimwear) : this.getRandomElement(this.lingerie);
        const outfitLine = `наряд: ${outfit}`;
        let parts = [
            this.getRandomElement(this.wardrobeLead),
            outfitLine,
            this.getRandomElement(this.skinForward),
            this.getRandomElement(this.noModest),
            this.getRandomElement(this.styles),
            this.getRandomElement(this.characters),
            this.getRandomElement(this.hair),
            `цветовая схема: ${this.getRandomElement(this.colors)}`,
            this.getRandomElement(this.poses),
            this.getRandomElement(this.locations),
            this.getRandomElement(this.effects),
            mood,
            style,
        ];

        let prompt = parts.join(', ');

        while (prompt.length > 400 && parts.length > 4) {
            parts.pop();
            prompt = parts.join(', ');
        }

        if (prompt.length > 400) {
            prompt = prompt.slice(0, 397) + '...';
        }

        return prompt;
    }

    generateMultiplePrompts(count = 5, options = {}) {
        const prompts = [];
        for (let i = 0; i < count; i++) {
            prompts.push(this.generatePrompt(options));
        }
        return prompts;
    }
