  _randomInt(max) {
    return Math.floor(Math.random() * max);
  }

  _собратьПромпт(объект, действие, окружение, освещение, настроение, стиль) {
    let prompt = `${объект}, ${действие} ${окружение}, ${освещение}, ${настроение}, ${стиль}.`;
    prompt = prompt.charAt(0).toUpperCase() + prompt.slice(1);
    return prompt;
  }

  // Генерация уникальной комбинации индексов (без повторений)
  _уникальнаяКомбинация(maxПопыток = 100) {
    for (let i = 0; i < maxПопыток; i++) {
      const combo = [
        this._randomInt(this.объект.length),
        this._randomInt(this.действие.length),
        this._randomInt(this.окружение.length),
        this._randomInt(this.освещение.length),
        this._randomInt(this.настроение.length),
        this._randomInt(this.стиль.length)
      ];
      const key = combo.join('|');
      if (!this.использованныеКомбинации.has(key)) {
        this.использованныеКомбинации.add(key);
        return combo;
      }
    }
    // Если не удалось найти уникальную (маловероятно, почти все комбинации исчерпаны),
    // возвращаем случайную и не добавляем в историю (чтобы не зацикливаться)
    return [
      this._randomInt(this.объект.length),
      this._randomInt(this.действие.length),
      this._randomInt(this.окружение.length),
      this._randomInt(this.освещение.length),
      this._randomInt(this.настроение.length),
      this._randomInt(this.стиль.length)
    ];
  }

  generatePrompt(maxLength = 400) {
    const combo = this._уникальнаяКомбинация();
    let объект = this.объект[combo[0]];
    let действие = this.действие[combo[1]];
    let окружение = this.окружение[combo[2]];
    let освещение = this.освещение[combo[3]];
    let настроение = this.настроение[combo[4]];
    let стиль = this.стиль[combo[5]];

    let prompt = this._собратьПромпт(объект, действие, окружение, освещение, настроение, стиль);

    // Если длина превышает лимит, удаляем последние блоки
    if (prompt.length > maxLength) {
      let варианты = [объект, действие, окружение, освещение, настроение, стиль];
      for (let i = варианты.length - 1; i >= 0; i--) {
        варианты[i] = "";
        let новыйПромпт = this._собратьПромпт(...варианты);
        // Убираем лишние запятые и точки
        новыйПромпт = новыйПромпт.replace(/, , /g, ", ").replace(/, ,/g, ",").replace(/,\s*\./g, ".");
        if (новыйПромпт.length <= maxLength) {
          return новыйПромпт;
        }
      }
      // Если всё равно длинный - обрезаем
      if (prompt.length > maxLength) {
        prompt = prompt.slice(0, maxLength - 3) + "...";
      }
    }
    return prompt;
  }

  // Сброс истории (если нужно начать заново)
  сброситьИсторию() {
    this.использованныеКомбинации.clear();
  }
