  _randomInt(max) {
    return Math.floor(Math.random() * max);
  }

  // Собирает строку объекта из пяти случайных частей
  _собратьОбъект() {
    const возр = this.возраст[this._randomInt(this.возраст.length)];
    const фиг = this.фигура[this._randomInt(this.фигура.length)];
    const гл = this.глаза[this._randomInt(this.глаза.length)];
    const вол = this.волосыПрическа[this._randomInt(this.волосыПрическа.length)];
    const куп = this.купальник[this._randomInt(this.купальник.length)];
    return `${возр}, ${фиг}, ${гл}, ${вол}, лёгкий макияж, ${куп}`;
  }

  // Сборка окончательного промпта из 8 логических блоков (объект — уже склеенный)
  _собратьПромпт(объект, действие, окружение, освещение, настроение, стиль, ракурс, эмоции) {
    let prompt = `${объект}, ${действие} ${окружение}, ${освещение}, ${настроение}, ${стиль}, ${ракурс}, ${эмоции}.`;
    prompt = prompt.replace(/, , /g, ", ").replace(/, ,/g, ",").replace(/,\s*\./g, ".");
    prompt = prompt.charAt(0).toUpperCase() + prompt.slice(1);
    return prompt;
  }

  // Генерирует массив из 12 случайных индексов (0–14) для всех категорий, уникальный в рамках сессии
  _случайныеИндексы() {
    return [
      this._randomInt(this.возраст.length),
      this._randomInt(this.фигура.length),
      this._randomInt(this.глаза.length),
      this._randomInt(this.волосыПрическа.length),
      this._randomInt(this.купальник.length),
      this._randomInt(this.действие.length),
      this._randomInt(this.окружение.length),
      this._randomInt(this.освещение.length),
      this._randomInt(this.настроение.length),
      this._randomInt(this.стиль.length),
      this._randomInt(this.ракурс.length),
      this._randomInt(this.эмоции.length)
    ];
  }

  _уникальнаяКомбинация(maxПопыток = 2000) {
    for (let i = 0; i < maxПопыток; i++) {
      const combo = this._случайныеИндексы();
      const key = combo.join('|');
      if (!this.использованныеКомбинации.has(key)) {
        this.использованныеКомбинации.add(key);
        return combo;
      }
    }
    // На случай бесконечного цикла (практически невозможно с учётом 15^12 комбинаций)
    return this._случайныеИндексы();
  }

  generatePrompt(maxLength = 1500) {
    const combo = this._уникальнаяКомбинация();
    // Собираем объект из первых пяти индексов комбинации
    const объект = [
      this.возраст[combo[0]],
      this.фигура[combo[1]],
      this.глаза[combo[2]],
      this.волосыПрическа[combo[3]],
      this.купальник[combo[4]]
    ];
    // Вручную склеиваем, добавляя "лёгкий макияж"
    const объектСтрока = `${объект[0]}, ${объект[1]}, ${объект[2]}, ${объект[3]}, лёгкий макияж, ${объект[4]}`;

    const действие = this.действие[combo[5]];
    const окружение = this.окружение[combo[6]];
    const освещение = this.освещение[combo[7]];
    const настроение = this.настроение[combo[8]];
    const стиль = this.стиль[combo[9]];
    const ракурс = this.ракурс[combo[10]];
    const эмоции = this.эмоции[combo[11]];

    let prompt = this._собратьПромпт(объектСтрока, действие, окружение, освещение, настроение, стиль, ракурс, эмоции);

    // Дополнение до 1500 символов техническими тегами, если нужно
    if (prompt.length < maxLength) {
      const filler = " hyperdetailed, sharp focus, intricate texture, 8k resolution, subsurface scattering on skin, caustics in water, film grain, HDR, cinematic lighting, ray tracing, trending on ArtStation, Unreal Engine 5 render, photorealistic, professional photography, high contrast, vivid colors, rich shadows, specular highlights, deep depth of field, ultra detailed, splash art, conceptual design, volumetric light, elegant composition.";
      // Убираем точку в конце если есть
      if (prompt.endsWith('.')) prompt = prompt.slice(0, -1);
      prompt += ',' + filler;
      // При необходимости добавляем ещё порции филлера
      while (prompt.length < maxLength) {
        prompt += " " + filler.slice(0, maxLength - prompt.length - 1);
      }
      // Аккуратно обрезаем ровно до maxLength
      if (prompt.length > maxLength) {
        prompt = prompt.slice(0, maxLength - 3) + "...";
      }
    }

    return prompt;
  }

  сброситьИсторию() {
    this.использованныеКомбинации.clear();
  }
