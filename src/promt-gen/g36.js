    getRandomElement(array) {
        return array[Math.floor(Math.random() * array.length)];
    }

    /**
     * Non-explicit fashion/editorial lingerie prompt (18+), no nude/explicit language.
     */
    generatePrompt(options = {}) {
        const opts = options && typeof options === "object" ? options : {};
        const { style = "ультрадетально, фотореализм, редакционное качество" } = opts;

        const parts = [
            this.getRandomElement(this.styles),
            this.getRandomElement(this.subjects),
            this.getRandomElement(this.lingerie),
            `локация: ${this.getRandomElement(this.locations)}`,
            `свет: ${this.getRandomElement(this.lighting)}`,
            this.getRandomElement(this.camera),
            this.getRandomElement(this.composition),
            this.getRandomElement(this.finish),
            style,
        ];

        let prompt = parts.join(", ");

        while (prompt.length > 400 && parts.length > 4) {
            parts.pop();
            prompt = parts.join(", ");
        }
        if (prompt.length > 400) {
            prompt = prompt.slice(0, 397) + "...";
        }

        return prompt;
    }

    generateMultiplePrompts(count = 5, options = {}) {
        const prompts = [];
        for (let i = 0; i < count; i++) {
            prompts.push(this.generatePrompt(options));
        }
        return prompts;
    }
